test("a config that names a service its clients do not have is a usage error with a reason", when, () => {
  // A description that cannot be assembled is something to fix in the file, not a run that failed.
  const dir = checkout({ ...config, clients: { billing: { service: "nowhere", operations: {} } } });
  const { status, err } = witness(["--config", "acme.config.json", "help"], dir);
  equal(status, 2);
  match(err, /client "billing" names service "nowhere", which is not declared/);
});

/**
 * The registry, not a list somebody kept.
 *
 * `skill.test.ts` hands `Skill` a `commands: [...]` it builds itself, so a verb that never reached the
 * skill could not fail anything — and three of them did not. `config`, `init` and `skill` were
 * registered on the command line and missing from the instructions, which are the only thing an agent
 * reads. This asks the real binary for both lists and compares them, so the two cannot part again.
 *
 * Parsed out of `usage()` because that is where the registered names actually surface: a noun is
 * indented two, its verbs four.
 */
const registered = (help: string): { noun: string; verbs: string[] }[] => {
  const nouns: { noun: string; verbs: string[] }[] = [];
  for (const line of help.split("\n")) {
    const noun = /^ {2}(\S+)/.exec(line);
    if (noun) {
      nouns.push({ noun: noun[1], verbs: [] });
      continue;
    }
    const verb = /^ {4}(\S+)/.exec(line);
    if (verb && nouns.length) nouns[nouns.length - 1].verbs.push(verb[1]);
  }
  return nouns;
};

test("every noun and verb the command line registers is in the generated skill", when, () => {
  const dir = checkout(config);
  const help = witness(["--config", "acme.config.json", "help"], dir);
  const generated = witness(["--config", "acme.config.json", "skill"], dir);
  equal(help.status, 0);
  equal(generated.status, 0);

  // What the file itself says a reader types, so this does not pin how the suite was invoked.
  const tool = /^Generated by `(.+) skill`/m.exec(generated.out)?.[1];
  ok(tool, "the skill says what generated it");

  const nouns = registered(help.out);
  // The ones that exist before a description does, and are therefore the ones somebody reaches for
  // first. They were the three missing, so a parse that quietly found nothing must not pass.
  for (const expected of ["config", "init", "skill", "stack", "order"]) {
    ok(nouns.some(n => n.noun === expected), `the command line still registers ${expected}`);
  }
  for (const { noun, verbs } of nouns) {
    ok(generated.out.includes(`- \`${tool} ${noun}\` — `), `noun \`${noun}\` is registered but absent from the skill`);
    for (const verb of verbs) {
      ok(generated.out.includes(`- \`${noun} ${verb}\` — `), `verb \`${noun} ${verb}\` is registered but absent from the skill`);
    }
  }
});

test("skill --write refreshes the copy on disk, rather than leaving the one init wrote", when, () => {
  const dir = mkdtempSync(path.join(tmpdir(), "witness-skill-write-"));
  writeFileSync(path.join(dir, ".env"), "");
  equal(witness(["init"], dir).status, 0);
  const at = path.join(dir, ".witness", "SKILL.md");
  writeFileSync(at, "# whatever was true the day this directory was made\n");

  // From a subdirectory, because `skill > .witness/SKILL.md` — the instruction this replaces — writes
  // wherever the reader happens to be standing.
  const nested = path.join(dir, "apps", "web");
  mkdirSync(nested, { recursive: true });
  const written = witness(["skill", "--write"], nested);
  equal(written.status, 0);
  match(written.out, /^wrote /);
  const refreshed = readFileSync(at, "utf8");
  match(refreshed, /^---\nname: /);
  // The command a reader with no description reaches for first, which is what this file exists to say.
  match(refreshed, / init` — make a \.witness\//);
});

test("init makes a .witness that the next command finds", when, () => {
  // The bootstrap: nothing configured, nothing to point at, and the description generated from the types.
  const dir = mkdtempSync(path.join(tmpdir(), "witness-init-"));
  writeFileSync(path.join(dir, ".env"), "");
  const made = witness(["init"], dir);
  equal(made.status, 0);
  match(made.out, /wrote \.witness\/config\.jsonc/);
  match(made.out, /wrote \.witness\/\.gitignore/);
  match(made.out, /wrote \.witness\/SKILL\.md/);

  // What runs leave behind is ignored by the directory itself, not by the project's own .gitignore.
  match(readFileSync(path.join(dir, ".witness", ".gitignore"), "utf8"), /^artifacts\/$/m);
  // A description, instructions, and what not to commit. Nothing to import and nothing to compile:
  // the whole point is that a project describes its product rather than programming against it.
  deepEqual(readdirSync(path.join(dir, ".witness")).sort(), [".gitignore", "SKILL.md", "config.jsonc"]);

  const nested = path.join(dir, "apps", "web");
  mkdirSync(nested, { recursive: true });
  const where = JSON.parse(witness(["config", "where"], nested).out) as Record<string, string>;
  equal(where.directory, path.join(realpathSync(dir), ".witness"));
  equal(where.checkout, realpathSync(dir));
  equal(where.found, ".witness");
});

test("init twice keeps what is there", when, () => {
  const dir = mkdtempSync(path.join(tmpdir(), "witness-init-twice-"));
  witness(["init"], dir);
  writeFileSync(path.join(dir, ".witness", "config.jsonc"), '{ "name": "mine" }');
  const again = witness(["init"], dir);
  match(again.out, /already has everything — nothing written/);
  equal(readFileSync(path.join(dir, ".witness", "config.jsonc"), "utf8"), '{ "name": "mine" }');
});

test("a described project needs no --config from anywhere inside it", when, () => {
  const dir = mkdtempSync(path.join(tmpdir(), "witness-found-"));
  mkdirSync(path.join(dir, ".witness"), { recursive: true });
  writeFileSync(path.join(dir, ".env"), "");
  writeFileSync(path.join(dir, ".witness", "config.jsonc"), `// the acme stack\n${JSON.stringify(config)}`);
  const nested = path.join(dir, "packages", "api");
  mkdirSync(nested, { recursive: true });
  const run = witness(["help"], nested);
  equal(run.status, 0);
  match(run.out, /acme — drive the local stack/);
});

test("config where says which description is in force, and why", when, () => {
  const dir = checkout(config);
  const where = JSON.parse(witness(["--config", "acme.config.json", "config", "where"], dir).out) as Record<string, string>;
  equal(where.config, path.join(realpathSync(dir), "acme.config.json"));
  equal(where.found, "--config");
  match(where.checkout, /from the config's `root` markers/);
});
