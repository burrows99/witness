import { deepEqual, equal, match, ok } from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, realpathSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { test } from "node:test";
import { tmpdir } from "node:os";
import * as path from "node:path";

import { withoutComments } from "../src/config/load.ts";

const binary = new URL("cli.ts", import.meta.url).pathname;

/** The binary assembles a whole system, so it needs the browser half installed to start at all. */
const havePlaywright = await import("@playwright/test").then(
  () => true,
  () => false,
);
const when = { skip: havePlaywright ? false : "needs @playwright/test" };

/** A checkout with a marker file and a config in it, and the CLI run from inside it. */
const checkout = (config: Record<string, unknown>): string => {
  const dir = mkdtempSync(path.join(tmpdir(), "witness-cli-"));
  writeFileSync(path.join(dir, "marker"), "");
  writeFileSync(path.join(dir, ".env"), "");
  writeFileSync(path.join(dir, "acme.config.json"), JSON.stringify(config));
  return dir;
};

const witness = (args: string[], cwd = tmpdir()): { status: number; out: string; err: string } => {
  const run = spawnSync(process.execPath, ["--disable-warning=MODULE_TYPELESS_PACKAGE_JSON", binary, ...args], { cwd, encoding: "utf8" });
  return { status: run.status ?? -1, out: run.stdout, err: run.stderr };
};

const config = {
  name: "acme",
  root: ["marker"],
  services: { api: { port: 3002 } },
  api: { service: "api", operations: { "orders.show": { path: "/v1/orders/{orderId}" } } },
  cli: { order: { summary: "orders", verbs: { show: { operation: "orders.show", args: ["orderId"] } } } },
};

test("a template can be printed before there is a config to load", when, () => {
  // Describing a product is the one thing that happens before a config exists.
  const { status, out } = witness(["config", "template"]);
  equal(status, 0);
  match(out, /^\/\/ A witness config, generated by/);
  deepEqual(Object.keys(JSON.parse(withoutComments(out))).slice(0, 3), ["name", "root", "services"]);
});

test("run where there is no .witness, it says how to make one", when, () => {
  const { status, err } = witness(["stack", "status"]);
  equal(status, 2);
  match(err, /no \.witness\/ in .* or any directory above it/);
  match(err, /Run `witness init` to make one, or pass --config <file>/);
});

test("an unknown config verb is a 2, not a stack trace", when, () => {
  const { status, err } = witness(["config", "nonsense"]);
  equal(status, 2);
  match(err, /unknown: config nonsense/);
});

test("a config gives the command line the product's own vocabulary", when, () => {
  const dir = checkout(config);
  const { status, out } = witness(["--config", "acme.config.json", "help"], dir);
  equal(status, 0);
  match(out, /acme — drive the local stack/);
  match(out, /order\s+orders/);
  match(out, /show\s+<orderId>/);
  // The generic half is there too, and so is the template, without being declared.
  match(out, /stack\s+what is up/);
  match(out, /config\s+the description this tool reads/);
});

test("the config can come from the environment instead of a flag", when, () => {
  const dir = checkout(config);
  const run = spawnSync(process.execPath, ["--disable-warning=MODULE_TYPELESS_PACKAGE_JSON", binary, "help"], {
    cwd: dir,
    encoding: "utf8",
    env: { ...process.env, WITNESS_CONFIG: "acme.config.json" },
  });
  equal(run.status, 0);
  match(run.stdout, /acme — drive the local stack/);
});

test("asking for something that does not exist is a 2", when, () => {
  const dir = checkout(config);
  equal(witness(["--config", "acme.config.json", "nonsense"], dir).status, 2);
  equal(witness(["--config", "acme.config.json", "order", "nonsense"], dir).status, 2);
  match(witness(["--config", "acme.config.json", "nonsense"], dir).err, /unknown command: nonsense/);
});

test("a missing argument says which one", when, () => {
  const dir = checkout(config);
  const { status, err } = witness(["--config", "acme.config.json", "order", "show"], dir);
  equal(status, 2);
  match(err, /missing <orderId>/);
});

test("a config file may carry the comments that explain it", when, () => {
  const dir = checkout(config);
  writeFileSync(path.join(dir, "acme.config.json"), `// what this stack is\n${JSON.stringify(config)}\n`);
  const { status, out } = witness(["--config", "acme.config.json", "help"], dir);
  equal(status, 0);
  ok(out.includes("acme"));
});

test("a config that names a service its clients do not have is a usage error with a reason", when, () => {
  // A description that cannot be assembled is something to fix in the file, not a run that failed.
  const dir = checkout({ ...config, clients: { billing: { service: "nowhere", operations: {} } } });
  const { status, err } = witness(["--config", "acme.config.json", "help"], dir);
  equal(status, 2);
  match(err, /client "billing" names service "nowhere", which is not declared/);
});

test("init makes a .witness that the next command finds", when, () => {
  // The bootstrap: nothing configured, nothing to point at, and the description generated from the types.
  const dir = mkdtempSync(path.join(tmpdir(), "witness-init-"));
  writeFileSync(path.join(dir, ".env"), "");
  const made = witness(["init"], dir);
  equal(made.status, 0);
  match(made.out, /wrote \.witness\/config\.jsonc/);
  match(made.out, /wrote \.witness\/\.gitignore/);
  match(made.out, /wrote \.witness\/SKILL\.md/);

  // What runs leave behind is ignored by the directory itself, not by the project's own .gitignore.
  match(readFileSync(path.join(dir, ".witness", ".gitignore"), "utf8"), /^artifacts\/$/m);
  // A description, instructions, and what not to commit. Nothing to import and nothing to compile:
  // the whole point is that a project describes its product rather than programming against it.
  deepEqual(readdirSync(path.join(dir, ".witness")).sort(), [".gitignore", "SKILL.md", "config.jsonc"]);

  const nested = path.join(dir, "apps", "web");
  mkdirSync(nested, { recursive: true });
  const where = JSON.parse(witness(["config", "where"], nested).out) as Record<string, string>;
  equal(where.directory, path.join(realpathSync(dir), ".witness"));
  equal(where.checkout, realpathSync(dir));
  equal(where.found, ".witness");
});

test("init twice keeps what is there", when, () => {
  const dir = mkdtempSync(path.join(tmpdir(), "witness-init-twice-"));
  witness(["init"], dir);
  writeFileSync(path.join(dir, ".witness", "config.jsonc"), '{ "name": "mine" }');
  const again = witness(["init"], dir);
  match(again.out, /already has everything — nothing written/);
  equal(readFileSync(path.join(dir, ".witness", "config.jsonc"), "utf8"), '{ "name": "mine" }');
});

test("a described project needs no --config from anywhere inside it", when, () => {
  const dir = mkdtempSync(path.join(tmpdir(), "witness-found-"));
  mkdirSync(path.join(dir, ".witness"), { recursive: true });
  writeFileSync(path.join(dir, ".env"), "");
  writeFileSync(path.join(dir, ".witness", "config.jsonc"), `// the acme stack\n${JSON.stringify(config)}`);
  const nested = path.join(dir, "packages", "api");
  mkdirSync(nested, { recursive: true });
  const run = witness(["help"], nested);
  equal(run.status, 0);
  match(run.out, /acme — drive the local stack/);
});

test("config where says which description is in force, and why", when, () => {
  const dir = checkout(config);
  const where = JSON.parse(witness(["--config", "acme.config.json", "config", "where"], dir).out) as Record<string, string>;
  equal(where.config, path.join(realpathSync(dir), "acme.config.json"));
  equal(where.found, "--config");
  match(where.checkout, /from the config's `root` markers/);
});
